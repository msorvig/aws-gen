fn emit_query_op(
    out:    &mut String,
    ctx:    &EmitCtx<'_>,
    name:   &str,
    op:     &crate::model::Operation,
) {
    let rt = ctx.runtime_crate;
    let fn_name    = to_snake(name);
    let endpoint   = &ctx.model.metadata.endpoint_prefix;
    let version    = &ctx.model.metadata.api_version;

    let input_type  = op.input.as_ref().map(|r| to_pascal(&r.shape));
    let output_type = op.output.as_ref()
        .map(|r| to_pascal(&r.shape))
        .unwrap_or_else(|| "()".to_string());

    // Determine if we need to unwrap a resultWrapper intermediate element.
    //
    // EC2  → resultWrapper = "DescribeInstancesResponse" (ends with "Response")
    //        quick-xml reads root element as the struct directly → no envelope needed.
    // IAM  → resultWrapper = "GetUserResult" (ends with "Result")
    //        Response body has an extra <GetUserResult> child wrapping the output.
    let wrapper_element: Option<&str> = op.result_wrapper.as_deref().and_then(|rw| {
        if output_type != "()" && !rw.ends_with("Response") {
            Some(rw)
        } else {
            None
        }
    });

    // Emit a private envelope struct so quick-xml can unwrap the intermediate element.
    if let Some(wrapper) = wrapper_element {
        let env_name = format!("{name}Envelope__");
        writeln!(out, "#[derive(serde::Deserialize)]").unwrap();
        writeln!(out, "struct {env_name} {{").unwrap();
        writeln!(out, "    #[serde(rename = \"{wrapper}\")]").unwrap();
        writeln!(out, "    result: {output_type},").unwrap();
        writeln!(out, "}}").unwrap();
        writeln!(out).unwrap();
    }

    let input_param = input_type.as_ref()
        .map(|t| format!(", input: {t}"))
        .unwrap_or_default();

    writeln!(out, "pub async fn {fn_name}(").unwrap();
    writeln!(out, "    client: &Client{input_param},").unwrap();
    writeln!(out, ") -> Result<{output_type}, AwsError> {{").unwrap();

    if input_type.is_some() {
        writeln!(out, "    use {rt}::aws::query_proto::QueryEncode as _;").unwrap();
        writeln!(out, "    let mut params: Vec<(String, String)> = vec![];").unwrap();
        writeln!(out, "    input.encode(\"\", &mut params);").unwrap();
    } else {
        writeln!(out, "    let params: Vec<(String, String)> = vec![];").unwrap();
    }

    if output_type == "()" {
        writeln!(out, "    client.query_request_void(\"{endpoint}\", \"{version}\", \"{name}\", params).await").unwrap();
    } else if wrapper_element.is_some() {
        let env_name = format!("{name}Envelope__");
        writeln!(out, "    let envelope: {env_name} = client.query_request(\"{endpoint}\", \"{version}\", \"{name}\", params).await?;").unwrap();
        writeln!(out, "    Ok(envelope.result)").unwrap();
    } else {
        writeln!(out, "    client.query_request(\"{endpoint}\", \"{version}\", \"{name}\", params).await").unwrap();
    }

    writeln!(out, "}}").unwrap();
    writeln!(out).unwrap();
}

fn emit_json_op(
    out:    &mut String,
    ctx:    &EmitCtx<'_>,
    name:   &str,
    op:     &crate::model::Operation,
) {
    let fn_name      = to_snake(name);
    let endpoint     = &ctx.model.metadata.endpoint_prefix;
    let target_pfx   = ctx.model.metadata.target_prefix.as_deref().unwrap_or("");
    let target       = format!("{target_pfx}.{name}");

    let input_type  = op.input.as_ref().map(|r| to_pascal(&r.shape));
    let output_type = op.output.as_ref()
        .map(|r| to_pascal(&r.shape))
        .unwrap_or_else(|| "()".to_string());

    let input_param = input_type.as_ref()
        .map(|t| format!(", input: {t}"))
        .unwrap_or_default();

    writeln!(out, "pub async fn {fn_name}(").unwrap();
    writeln!(out, "    client: &Client{input_param},").unwrap();
    writeln!(out, ") -> Result<{output_type}, AwsError> {{").unwrap();

    if input_type.is_some() {
        writeln!(out, "    client.json_request(\"{endpoint}\", \"{target}\", &input).await").unwrap();
    } else {
        writeln!(out, "    client.json_request(\"{endpoint}\", \"{target}\", &serde_json::json!({{}})).await").unwrap();
    }

    writeln!(out, "}}").unwrap();
    writeln!(out).unwrap();
}

fn emit_rest_json_op(
    out:    &mut String,
    ctx:    &EmitCtx<'_>,
    name:   &str,
    op:     &crate::model::Operation,
) {
    use crate::model::ShapeRef;

    let rt           = ctx.runtime_crate;
    let fn_name      = to_snake(name);
    let endpoint     = &ctx.model.metadata.endpoint_prefix;

    let http         = op.http.as_ref();
    let method       = http.map(|h| h.method.as_str()).unwrap_or("POST");
    let uri_template = http.map(|h| h.request_uri.as_str()).unwrap_or("/");

    let input_type  = op.input.as_ref().map(|r| to_pascal(&r.shape));
    let output_type = op.output.as_ref()
        .map(|r| to_pascal(&r.shape))
        .unwrap_or_else(|| "()".to_string());

    let input_param = input_type.as_ref()
        .map(|t| format!(", input: {t}"))
        .unwrap_or_default();

    writeln!(out, "pub async fn {fn_name}(").unwrap();
    writeln!(out, "    client: &Client{input_param},").unwrap();
    writeln!(out, ") -> Result<{output_type}, AwsError> {{").unwrap();

    if let Some(_) = input_type {
        // Collect members by location from the input shape
        let input_shape_name = op.input.as_ref().map(|r| r.shape.as_str()).unwrap_or("");
        let members: Vec<(String, ShapeRef)> = ctx.model.shapes
            .get(input_shape_name)
            .map(|s| s.members.iter().map(|(k, v)| (k.clone(), v.clone())).collect())
            .unwrap_or_default();

        // Build URI: replace {TemplateName} segments
        // Template segments use PascalCase in the spec (e.g., {FunctionName})
        // URI template → collect uri-location members
        // URI template → collect uri-location members
        let uri_members: Vec<_> = members.iter()
            .filter(|(_, r)| r.location.as_deref() == Some("uri"))
            .collect();

        // Rewrite the template format! — replace {X} with {x} for Rust format! compat
        let mut fmt_str = uri_template.to_string();
        let mut fmt_args = String::new();
        for (mname, _mref) in &uri_members {
            let placeholder = format!("{{{mname}}}");
            let snake = to_snake(mname);
            if fmt_str.contains(&placeholder) {
                fmt_str = fmt_str.replace(&placeholder, "{}");
                fmt_args.push_str(&format!(
                    "    &{rt}::aws::client::percent_encode(&input.{snake}),\n",
                ));
            }
        }

        if uri_members.is_empty() {
            writeln!(out, "    let uri = \"{uri_template}\";").unwrap();
        } else {
            writeln!(out, "    let uri = format!(\"{fmt_str}\",").unwrap();
            writeln!(out, "{fmt_args}    );").unwrap();
        }

        // Collect querystring members
        let qs_members: Vec<_> = members.iter()
            .filter(|(_, r)| r.location.as_deref() == Some("querystring"))
            .collect();

        writeln!(out, "    let mut _query: Vec<(String, String)> = vec![];").unwrap();
        for (mname, _mref) in &qs_members {
            let snake = to_snake(mname);
            let wire  = _mref.wire_name(mname);
            writeln!(out,
                "    if let Some(ref v) = input.{snake} {{ _query.push((\"{wire}\".into(), v.to_string())); }}",
            ).unwrap();
        }

        // Collect header members
        let hdr_members: Vec<_> = members.iter()
            .filter(|(_, r)| matches!(r.location.as_deref(), Some("header") | Some("headers")))
            .collect();

        writeln!(out, "    let mut _headers: Vec<(String, String)> = vec![];").unwrap();
        for (mname, mref) in &hdr_members {
            let snake = to_snake(mname);
            let hdr_name = mref.location_name.as_deref().unwrap_or(mname.as_str());
            writeln!(out,
                "    if let Some(ref v) = input.{snake} {{ _headers.push((\"{hdr_name}\".into(), v.to_string())); }}",
            ).unwrap();
        }

        if output_type == "()" {
            writeln!(out, "    client.rest_json_request_void(\"{endpoint}\", \"{method}\", &uri, &_query, &_headers, &input).await").unwrap();
        } else {
            writeln!(out, "    client.rest_json_request(\"{endpoint}\", \"{method}\", &uri, &_query, &_headers, &input).await").unwrap();
        }
    } else {
        writeln!(out, "    let uri = \"{uri_template}\";").unwrap();
        writeln!(out, "    let empty: serde_json::Value = serde_json::json!({{}});").unwrap();
        if output_type == "()" {
            writeln!(out, "    client.rest_json_request_void(\"{endpoint}\", \"{method}\", uri, &[], &[], &empty).await").unwrap();
        } else {
            writeln!(out, "    client.rest_json_request(\"{endpoint}\", \"{method}\", uri, &[], &[], &empty).await").unwrap();
        }
    }

    writeln!(out, "}}").unwrap();
    writeln!(out).unwrap();
}

fn emit_rest_xml_op(
    out:    &mut String,
    ctx:    &EmitCtx<'_>,
    name:   &str,
    op:     &crate::model::Operation,
) {
    use crate::model::ShapeRef;

    let rt           = ctx.runtime_crate;
    let fn_name      = to_snake(name);
    let endpoint     = &ctx.model.metadata.endpoint_prefix;

    let http         = op.http.as_ref();
    let method       = http.map(|h| h.method.as_str()).unwrap_or("GET");
    let uri_template = http.map(|h| h.request_uri.as_str()).unwrap_or("/");

    // Split static query params from URI template (e.g. "/{Bucket}?list-type=2")
    let (uri_path, static_qs) = match uri_template.split_once('?') {
        Some((p, q)) => (p, Some(q)),
        None => (uri_template, None),
    };

    let input_type  = op.input.as_ref().map(|r| to_pascal(&r.shape));
    let output_type = op.output.as_ref()
        .map(|r| to_pascal(&r.shape))
        .unwrap_or_else(|| "()".to_string());

    let input_param = input_type.as_ref()
        .map(|t| format!(", input: {t}"))
        .unwrap_or_default();

    writeln!(out, "pub async fn {fn_name}(").unwrap();
    writeln!(out, "    client: &Client{input_param},").unwrap();
    writeln!(out, ") -> Result<{output_type}, AwsError> {{").unwrap();

    if input_type.is_some() {
        let input_shape_name = op.input.as_ref().map(|r| r.shape.as_str()).unwrap_or("");
        let members: Vec<(String, ShapeRef)> = ctx.model.shapes
            .get(input_shape_name)
            .map(|s| s.members.iter().map(|(k, v)| (k.clone(), v.clone())).collect())
            .unwrap_or_default();

        // URI template expansion
        let uri_members: Vec<_> = members.iter()
            .filter(|(_, r)| r.location.as_deref() == Some("uri"))
            .collect();

        let mut fmt_str = uri_path.to_string();
        let mut fmt_args = String::new();
        for (mname, _mref) in &uri_members {
            // Handle {Key+} greedy path params
            let placeholder = format!("{{{mname}}}");
            let placeholder_greedy = format!("{{{mname}+}}");
            let snake = to_snake(mname);
            if fmt_str.contains(&placeholder_greedy) {
                // Greedy: don't percent-encode slashes
                fmt_str = fmt_str.replace(&placeholder_greedy, "{}");
                fmt_args.push_str(&format!("    &input.{snake},\n"));
            } else if fmt_str.contains(&placeholder) {
                fmt_str = fmt_str.replace(&placeholder, "{}");
                fmt_args.push_str(&format!(
                    "    &{rt}::aws::client::percent_encode(&input.{snake}),\n",
                ));
            }
        }

        if uri_members.is_empty() {
            writeln!(out, "    let uri = \"{uri_path}\".to_string();").unwrap();
        } else {
            writeln!(out, "    let uri = format!(\"{fmt_str}\",").unwrap();
            writeln!(out, "{fmt_args}    );").unwrap();
        }

        // Querystring members
        let qs_members: Vec<_> = members.iter()
            .filter(|(_, r)| r.location.as_deref() == Some("querystring"))
            .collect();

        writeln!(out, "    let mut _query: Vec<(String, String)> = vec![];").unwrap();
        // Static query params from URI template
        if let Some(sq) = static_qs {
            for part in sq.split('&') {
                if let Some((k, v)) = part.split_once('=') {
                    writeln!(out, "    _query.push((\"{k}\".into(), \"{v}\".into()));").unwrap();
                }
            }
        }
        for (mname, mref) in &qs_members {
            let snake = to_snake(mname);
            let wire  = mref.wire_name(mname);
            writeln!(out,
                "    if let Some(ref v) = input.{snake} {{ _query.push((\"{wire}\".into(), v.to_string())); }}",
            ).unwrap();
        }

        // Header members (only scalars — lists/structs need custom serialization)
        let hdr_members: Vec<_> = members.iter()
            .filter(|(_, r)| matches!(r.location.as_deref(), Some("header") | Some("headers")))
            .filter(|(_, r)| {
                ctx.model.shapes.get(&r.shape)
                    .map(|s| matches!(s.shape_type.as_str(), "string" | "integer" | "long" | "boolean" | "float" | "double" | "timestamp"))
                    .unwrap_or(true)
            })
            .collect();

        writeln!(out, "    let mut _headers: Vec<(String, String)> = vec![];").unwrap();
        for (mname, mref) in &hdr_members {
            let snake = to_snake(mname);
            let hdr_name = mref.location_name.as_deref().unwrap_or(mname.as_str());
            writeln!(out,
                "    if let Some(ref v) = input.{snake} {{ _headers.push((\"{hdr_name}\".into(), v.to_string())); }}",
            ).unwrap();
        }

        if output_type == "()" {
            writeln!(out, "    client.rest_xml_request_void(\"{endpoint}\", \"{method}\", &uri, &_query, &_headers).await").unwrap();
        } else {
            writeln!(out, "    client.rest_xml_request(\"{endpoint}\", \"{method}\", &uri, &_query, &_headers).await").unwrap();
        }
    } else {
        writeln!(out, "    let uri = \"{uri_path}\";").unwrap();
        if let Some(sq) = static_qs {
            writeln!(out, "    let _query: Vec<(String, String)> = vec![").unwrap();
            for part in sq.split('&') {
                if let Some((k, v)) = part.split_once('=') {
                    writeln!(out, "        (\"{k}\".into(), \"{v}\".into()),").unwrap();
                }
            }
            writeln!(out, "    ];").unwrap();
            if output_type == "()" {
                writeln!(out, "    client.rest_xml_request_void(\"{endpoint}\", \"{method}\", uri, &_query, &[]).await").unwrap();
            } else {
                writeln!(out, "    client.rest_xml_request(\"{endpoint}\", \"{method}\", uri, &_query, &[]).await").unwrap();
            }
        } else {
            if output_type == "()" {
                writeln!(out, "    client.rest_xml_request_void(\"{endpoint}\", \"{method}\", uri, &[], &[]).await").unwrap();
            } else {
                writeln!(out, "    client.rest_xml_request(\"{endpoint}\", \"{method}\", uri, &[], &[]).await").unwrap();
            }
        }
    }

    writeln!(out, "}}").unwrap();
    writeln!(out).unwrap();
}

fn emit_map_type(
    out:       &mut String,
    ctx:       &EmitCtx<'_>,
    name:      &str,
    shape:     &crate::model::Shape,
    in_input:  bool,
    in_output: bool,
) {
    // Maps in query protocol: we emit a newtype wrapper around HashMap.
    // The QueryEncode impl serializes as flat key=value pairs using an
    // "entry.N.key" / "entry.N.value" pattern (used by some EC2 / SQS operations).
    // For JSON protocol, we just use HashMap directly (handled inline in rust_type_by_name).
    if !is_query_protocol(&ctx.model.metadata.protocol) { return; }
    let rt = ctx.runtime_crate;

    let rust_name = to_pascal(name);
    let k_type = shape.key.as_ref()
        .map(|r| rust_type_by_name(&r.shape, ctx.model, false))
        .unwrap_or_else(|| "String".to_string());
    let v_type = shape.value.as_ref()
        .map(|r| rust_type_by_name(&r.shape, ctx.model, false))
        .unwrap_or_else(|| "String".to_string());

    // Non-query protocols: emit a type alias. Field types reference to_pascal(shape_name)
    // which maps to this alias; serde handles HashMap<K,V> deserialization natively.
    if !is_query_protocol(&ctx.model.metadata.protocol) {
        writeln!(out, "pub type {rust_name} = std::collections::HashMap<{k_type}, {v_type}>;").unwrap();
        writeln!(out).unwrap();
        return;
    }

    let key_wire   = shape.key.as_ref().and_then(|r| r.location_name.as_deref()).unwrap_or("key");
    let value_wire = shape.value.as_ref().and_then(|r| r.location_name.as_deref()).unwrap_or("value");

    let mut derives = vec!["Debug", "Clone", "Default"];
    if in_output { derives.push("serde::Deserialize"); }
    writeln!(out, "#[derive({})]", derives.join(", ")).unwrap();
    writeln!(out, "pub struct {rust_name}(pub std::collections::HashMap<{k_type}, {v_type}>);").unwrap();
    writeln!(out).unwrap();

    if in_input {
        writeln!(out, "impl {rt}::aws::query_proto::QueryEncode for {rust_name} {{").unwrap();
        writeln!(out, "    fn encode(&self, prefix: &str, out: &mut Vec<(String, String)>) {{").unwrap();
        writeln!(out, "        for (i, (k, v)) in self.0.iter().enumerate() {{").unwrap();
        writeln!(out, "            let n = i + 1;").unwrap();
        writeln!(out, "            out.push((format!(\"{{prefix}}.{{n}}.{key_wire}\"), k.to_string()));").unwrap();
        writeln!(out, "            out.push((format!(\"{{prefix}}.{{n}}.{value_wire}\"), v.to_string()));").unwrap();
        writeln!(out, "        }}").unwrap();
        writeln!(out, "    }}").unwrap();
        writeln!(out, "}}").unwrap();
        writeln!(out).unwrap();
    }
}


