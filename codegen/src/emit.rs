use std::collections::HashSet;
use std::fmt::Write as FmtWrite;

use crate::model::{ServiceModel, Shape};
use crate::resolve::ReachableShapes;

// ─────────────────────────────────────────────────────────────────────────────
// Protocol helpers
// ─────────────────────────────────────────────────────────────────────────────

/// EC2 uses protocol "ec2" in the spec, but it's wire-compatible with "query".
fn is_query_protocol(proto: &str) -> bool {
    matches!(proto, "query" | "ec2")
}

// ─────────────────────────────────────────────────────────────────────────────
// Public entry point
// ─────────────────────────────────────────────────────────────────────────────

pub struct EmitCtx<'a> {
    pub model:           &'a ServiceModel,
    pub reachable:       &'a ReachableShapes,
    pub topo_order:      &'a [String],
    pub operations:      &'a [&'a str],
    pub service_name:    &'a str,
    /// Crate path for the aws-api runtime. Defaults to `"aws_api"`.
    /// Set to `"crate"` if the generated code lives inside the aws-api crate itself.
    pub runtime_crate:   &'a str,
}

pub fn emit(ctx: &EmitCtx<'_>) -> String {
    let mut out = String::with_capacity(64 * 1024);
    let proto = ctx.model.metadata.protocol.as_str();

    writeln!(out, "// Auto-generated by aws-codegen — DO NOT EDIT").unwrap();
    writeln!(out, "// service={} protocol={} version={}",
        ctx.service_name,
        proto,
        ctx.model.metadata.api_version,
    ).unwrap();
    // NOTE: the including module should add #[allow(dead_code, non_snake_case, ...)]
    writeln!(out).unwrap();
    let rt = ctx.runtime_crate;
    writeln!(out, "use {rt}::aws::{{Client, AwsError}};").unwrap();
    writeln!(out).unwrap();

    // Emit all shape types in dependency order
    for shape_name in ctx.topo_order {
        let Some(shape) = ctx.model.shapes.get(shape_name.as_str()) else { continue };

        // Skip primitives (string/integer/etc with no enum values) — they inline
        if shape.is_primitive() { continue; }

        let in_input  = ctx.reachable.input.contains(shape_name);
        let in_output = ctx.reachable.output.contains(shape_name);

        match shape.shape_type.as_str() {
            "structure" => emit_structure(&mut out, ctx, shape_name, shape, in_input, in_output),
            "list"      => emit_list_wrapper(&mut out, ctx, shape_name, shape, in_input, in_output),
            "map"       => emit_map_type(&mut out, ctx, shape_name, shape, in_input, in_output),
            "string" if shape.enum_values.is_some() => emit_string_enum(&mut out, ctx, shape_name, shape),
            _ => {}
        }
    }

    // Emit operation async functions
    for &op_name in ctx.operations {
        let Some(op) = ctx.model.operations.get(op_name) else { continue };
        match proto {
            "query"     => emit_query_op(&mut out, ctx, op_name, op),
            "json"      => emit_json_op(&mut out, ctx, op_name, op),
            "rest-json" => emit_rest_json_op(&mut out, ctx, op_name, op),
            "rest-xml"  => emit_rest_xml_op(&mut out, ctx, op_name, op),
            _           => emit_query_op(&mut out, ctx, op_name, op), // fallback
        }
    }

    out
}

