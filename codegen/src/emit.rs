// Name mangling utilities
// ─────────────────────────────────────────────────────────────────────────────

/// PascalCase → snake_case
pub fn to_snake(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 4);
    for (i, ch) in s.chars().enumerate() {
        if ch.is_uppercase() {
            if i > 0 {
                out.push('_');
            }
            out.push(ch.to_ascii_lowercase());
        } else {
            out.push(ch);
        }
    }
    // Escape Rust keywords
    match out.as_str() {
        "type" | "self" | "move" | "in" | "match" | "loop" | "use" | "return"
        | "for" | "if" | "else" | "let" | "mut" | "ref" | "static" | "fn" => {
            out.insert_str(0, "r#");
        }
        _ => {}
    }
    out
}

/// snake_case or PascalCase → PascalCase
pub fn to_pascal(s: &str) -> String {
    s.split('_')
        .map(|part| {
            let mut chars = part.chars();
            match chars.next() {
                None => String::new(),
                Some(first) => first.to_uppercase().collect::<String>() + chars.as_str(),
            }
        })
        .collect()
}

/// PascalCase → camelCase
fn to_camel(s: &str) -> String {
    let pascal = to_pascal(s);
    let mut chars = pascal.chars();
    match chars.next() {
        None => String::new(),
        Some(c) => c.to_lowercase().collect::<String>() + chars.as_str(),
    }
}

fn sanitize_enum_variant(s: &str) -> String {
    // Replace any non-alphanumeric char with underscore, then PascalCase.
    let cleaned: String = s.chars()
        .map(|c| if c.is_ascii_alphanumeric() { c } else { '_' })
        .collect();
    let pascal = to_pascal(&cleaned);
    // Ensure it starts with a letter
    if pascal.chars().next().map(|c| c.is_ascii_digit()).unwrap_or(false) {
        format!("V{pascal}")
    } else {
        pascal
    }
}

fn strip_html(s: &str) -> String {
    // Very basic HTML tag stripping for doc comments
    let mut out = String::with_capacity(s.len());
    let mut in_tag = false;
    for ch in s.chars() {
        match ch {
            '<' => in_tag = true,
            '>' => in_tag = false,
            _   => if !in_tag { out.push(ch); }
        }
    }
    out
}
