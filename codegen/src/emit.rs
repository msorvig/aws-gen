fn emit_query_op(
    out:    &mut String,
    ctx:    &EmitCtx<'_>,
    name:   &str,
    op:     &crate::model::Operation,
) {
    let rt = ctx.runtime_crate;
    let fn_name    = to_snake(name);
    let endpoint   = &ctx.model.metadata.endpoint_prefix;
    let version    = &ctx.model.metadata.api_version;

    let input_type  = op.input.as_ref().map(|r| to_pascal(&r.shape));
    let output_type = op.output.as_ref()
        .map(|r| to_pascal(&r.shape))
        .unwrap_or_else(|| "()".to_string());

    // Determine if we need to unwrap a resultWrapper intermediate element.
    //
    // EC2  → resultWrapper = "DescribeInstancesResponse" (ends with "Response")
    //        quick-xml reads root element as the struct directly → no envelope needed.
    // IAM  → resultWrapper = "GetUserResult" (ends with "Result")
    //        Response body has an extra <GetUserResult> child wrapping the output.
    let wrapper_element: Option<&str> = op.result_wrapper.as_deref().and_then(|rw| {
        if output_type != "()" && !rw.ends_with("Response") {
            Some(rw)
        } else {
            None
        }
    });

    // For result-wrapper unwrapping, emit a FromXml wrapper that extracts the child element.
    if let Some(wrapper) = wrapper_element {
        let env_name = format!("{name}Envelope__");
        writeln!(out, "struct {env_name};").unwrap();
        writeln!(out, "impl {env_name} {{").unwrap();
        writeln!(out, "    fn unwrap(node: &{rt}::aws::xml::XmlNode) -> Result<{output_type}, String> {{").unwrap();
        writeln!(out, "        let child = node.child(\"{wrapper}\")").unwrap();
        writeln!(out, "            .ok_or_else(|| \"missing {wrapper} element\".to_string())?;").unwrap();
        writeln!(out, "        {rt}::aws::xml::FromXml::from_xml(child)").unwrap();
        writeln!(out, "    }}").unwrap();
        writeln!(out, "}}").unwrap();
        writeln!(out).unwrap();
    }

    let input_param = input_type.as_ref()
        .map(|t| format!(", input: {t}"))
        .unwrap_or_default();

    writeln!(out, "pub async fn {fn_name}(").unwrap();
    writeln!(out, "    client: &Client{input_param},").unwrap();
    writeln!(out, ") -> Result<{output_type}, AwsError> {{").unwrap();

    if input_type.is_some() {
        writeln!(out, "    use {rt}::aws::query_proto::QueryEncode as _;").unwrap();
        writeln!(out, "    let mut params: Vec<(String, String)> = vec![];").unwrap();
        writeln!(out, "    input.encode(\"\", &mut params);").unwrap();
    } else {
        writeln!(out, "    let params: Vec<(String, String)> = vec![];").unwrap();
    }

    if output_type == "()" {
        writeln!(out, "    client.query_request_void(\"{endpoint}\", \"{version}\", \"{name}\", params).await").unwrap();
    } else if wrapper_element.is_some() {
        let env_name = format!("{name}Envelope__");
        // query_request returns the XML root; we need to unwrap the wrapper child
        writeln!(out, "    let root: {rt}::aws::xml::XmlNode = {{").unwrap();
        writeln!(out, "        use {rt}::aws::query_proto::QueryEncode as _;").unwrap();
        writeln!(out, "        // Build and send the request, get raw XML back").unwrap();
        writeln!(out, "        client.query_request_raw(\"{endpoint}\", \"{version}\", \"{name}\", params).await?").unwrap();
        writeln!(out, "    }};").unwrap();
        writeln!(out, "    {env_name}::unwrap(&root).map_err(|e| {rt}::aws::AwsError::XmlParse(e))").unwrap();
    } else {
        writeln!(out, "    client.query_request(\"{endpoint}\", \"{version}\", \"{name}\", params).await").unwrap();
    }

    writeln!(out, "}}").unwrap();
    writeln!(out).unwrap();
}

