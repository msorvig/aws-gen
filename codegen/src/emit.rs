/// The Rust field type for a member reference.
/// - `for_output`: lists become the wrapper struct, which is needed for XML deserialization.
///   For input, lists are also wrapper structs (consistent representation).
fn rust_field_type(ctx: &EmitCtx<'_>, member_ref: &crate::model::ShapeRef, for_output: bool) -> String {
    rust_type_by_name(&member_ref.shape, ctx.model, for_output)
}


pub fn rust_type_by_name(shape_name: &str, model: &ServiceModel, _for_output: bool) -> String {
    let Some(shape) = model.shapes.get(shape_name) else {
        return to_pascal(shape_name);
    };

    match shape.shape_type.as_str() {
        "string" => {
            if shape.enum_values.is_some() {
                to_pascal(shape_name)
            } else {
                "String".to_string()
            }
        }
        "integer"   => "i32".to_string(),
        "long"      => "i64".to_string(),
        "float"     => "f32".to_string(),
        "double"    => "f64".to_string(),
        "boolean"   => "bool".to_string(),
        "timestamp" => {
            // JSON protocols send timestamps as epoch floats; XML uses ISO 8601 strings.
            if matches!(model.metadata.protocol.as_str(), "json" | "rest-json") {
                "f64".to_string()
            } else {
                "String".to_string()
            }
        }
        "blob"      => "Vec<u8>".to_string(),
        "list"      => to_pascal(shape_name), // list shapes become wrapper structs
        "map" => {
            if is_query_protocol(&model.metadata.protocol) {
                // Query protocol: wrapper struct is emitted by emit_map_type
                to_pascal(shape_name)
            } else {
                // Non-query protocols: inline HashMap
                let k = shape.key.as_ref()
                    .map(|r| rust_type_by_name(&r.shape, model, false))
                    .unwrap_or_else(|| "String".to_string());
                let v = shape.value.as_ref()
                    .map(|r| rust_type_by_name(&r.shape, model, false))
                    .unwrap_or_else(|| "String".to_string());
                format!("std::collections::HashMap<{k}, {v}>")
            }
        }
        "structure" => to_pascal(shape_name),
        _ => "serde_json::Value".to_string(),
    }
}

